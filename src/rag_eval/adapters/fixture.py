"""DETERMINISTIC TEST FIXTURE. Never use for real RAG quality claims."""
import re
from time import perf_counter
from rag_eval.adapters.base import RAGAdapter
from rag_eval.config import ExperimentConfig, IndexInfo, Trace, Passage, digest

DOCS = {'fixture-doc-a': 'RAGBench is an evaluation studio. The application records retrieval traces and source identifiers.',
        'fixture-doc-b': 'The test fixture is not Project 6. Scores from the fixture must not be treated as benchmark results.',
        'fixture-doc-c': 'Faithfulness checks support in retrieved text. Context precision evaluates retrieval rank.'}


class FixtureAdapter(RAGAdapter):
    def __init__(self):
        self.indexes = {}

    def capabilities(self) -> dict:
        return {'protocol': 'fixture-only', 'retrievers': ['keyword'], 'chunk_units': ['characters'],
                'chunk_strategies': ['fixed'], 'supports_reindex': True, 'rerankers': []}

    def prepare_index(self, config: ExperimentConfig) -> IndexInfo:
        start_time = perf_counter()
        if config.chunk_unit != 'characters' or config.chunk_strategy != 'fixed' or config.retriever not in ('keyword',):
            raise ValueError('fixture supports fixed-character chunks and keyword only')
        chunks = []
        for did, text in DOCS.items():
            start = 0
            while start < len(text):
                part = text[start:start + config.chunk_size]
                chunks.append((did, f'{did}:{start}', part))
                if start + config.chunk_size >= len(text):
                    break
                start += config.chunk_size - config.chunk_overlap
        fp = digest({'docs': DOCS, 'size': config.chunk_size, 'overlap': config.chunk_overlap})
        self.indexes[fp] = chunks
        return IndexInfo(index_id='fixture-' + fp[:12], fingerprint=fp, chunk_count=len(chunks),
                         effective_config={'chunk_strategy': config.chunk_strategy, 'chunk_size': config.chunk_size,
                                           'chunk_overlap': config.chunk_overlap, 'chunk_unit': config.chunk_unit,
                                           'embedding_model': config.embedding_model}, indexing_ms=(perf_counter() - start_time) * 1000)

    def run_question(self, question: str, config: ExperimentConfig, index: IndexInfo) -> Trace:
        started = perf_counter()
        # This is deterministic keyword overlap for adapter tests, NOT a dense retriever or quality measurement.
        terms = set(re.findall(r'\w+', question.lower()))
        scored = []
        for did, cid, text in self.indexes[index.fingerprint]:
            count = len(terms & set(re.findall(r'\w+', text.lower())))
            scored.append((count, did, cid, text))
        scored.sort(key=lambda row: (-row[0], row[1], row[2]))
        passages = [Passage(document_id=did, chunk_id=cid, rank=i + 1, text=text, score=float(count), source='TEST FIXTURE')
                    for i, (count, did, cid, text) in enumerate(scored[:config.top_k])]
        return Trace(question=question, answer='[FIXTURE RESPONSE — NOT GENERATED BY PROJECT 6]',
                     passages=passages, effective_config={'retriever': config.retriever, 'top_k': config.top_k,
                     'generation_model': config.generation_model, 'prompt_version': config.prompt_version},
                     index_id=index.index_id, index_fingerprint=index.fingerprint,
                     retrieval_ms=(perf_counter() - started) * 1000, trace_metadata={'fixture_only': True})


def make_adapter(mode: str) -> RAGAdapter:
    if mode == 'fixture':
        return FixtureAdapter()
    if mode == 'project6_http':
        from rag_eval.adapters.project6_adapter import Project6HTTPAdapter
        return Project6HTTPAdapter()
    raise ValueError(f'unknown adapter: {mode}')
